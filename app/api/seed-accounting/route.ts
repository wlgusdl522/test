export async function GET() {
  try {
    const email = await requireViewerEmail();
    if (!(await isAdminEmail(email))) {
      return NextResponse.json({ error: '관리자만 실행할 수 있습니다.' }, { status: 403 });
    }

    const itemRecords: { keyValues: Record<string, string>; record: Record<string, string> }[] = [];
    for (const [시설, sections] of Object.entries(ACCOUNTING_ITEMS)) {
      for (const [구분, list] of Object.entries(sections) as ['수입' | '지출', Item[]][]) {
        for (const it of list) {
          const id = randomUUID();
          itemRecords.push({
            keyValues: { id },
            record: { id, 모듈: '회계', 항목명: it.항목명, 정렬순서: String(it.순서), 시설, 구분, 그룹: it.그룹 },
          });
        }
      }
    }

    const accountRecords: { keyValues: Record<string, string>; record: Record<string, string> }[] = [];
    for (const [시설, list] of Object.entries(BANK_ACCOUNTS)) {
      for (const a of list) {
        const id = randomUUID();
        accountRecords.push({
          keyValues: { id },
          record: { id, 시설, 은행명: a.은행명, 계좌번호: a.계좌번호, 비고: a.비고, 정렬순서: String(a.순서) },
        });
      }
    }

    await upsertKeyedRecords(BOARD_STAT_ITEM_TABLE, itemRecords);
    await upsertKeyedRecords(BOARD_BANK_ACCOUNT_TABLE, accountRecords);

    return NextResponse.json({ result: 'seeded', 항목: itemRecords.length, 계좌: accountRecords.length });
  } catch (err) {
    return NextResponse.json({ error: err instanceof Error ? err.message : String(err) }, { status: 500 });
  }
}
